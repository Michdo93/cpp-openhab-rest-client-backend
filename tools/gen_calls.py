"""Generates src/calls.cpp and methods.json from python-openhab-rest-client.

    python3 tools/gen_calls.py <cpp-openhab-rest-client>/tools/py2cpp.py \
        <python-openhab-rest-client>/openhab src/calls.cpp methods.json

calls.cpp maps "Class.method" plus a JSON object with named arguments to the method of
cpp-openhab-rest-client (openhabCall for REST calls, openhabOpenStream for event streams).
methods.json lists every method with its parameters for the test app.
"""
import importlib.util
import json
import sys

spec = importlib.util.spec_from_file_location("py2cpp", sys.argv[1])
py2cpp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(py2cpp)

CONV = {"str": "s_", "bool": "b_", "int": "i_", "float": "d_", "json": "j_"}


def call_expr(cls, m):
    req = [f'{CONV[t]}(a_(args, "{n}"))' for n, t, d, r in m.params if r]
    obj = f"openhab::{cls}(c).{m.name}"
    if not m.optional:
        return [f"return {obj}({', '.join(req)});"]
    out = [f"openhab::{cls}::{m.args_struct} a;"]
    for n, t, d, r in m.optional:
        out.append(f'set_(a.{py2cpp.cname(n)}, args, "{n}");')
    out.append(f"return {obj}({', '.join(req + ['a'])});")
    return out


def default_text(d):
    if d is None:
        return None
    try:
        return py2cpp.ast.literal_eval(d)
    except Exception:
        return py2cpp.ast.unparse(d)


def main():
    rest, streams, table = [], [], []
    for fname, c, methods in py2cpp.load_classes(sys.argv[2]):
        for m in methods.values():
            if m.private:
                continue
            lines = [f'    if (cls == "{c.name}" && m == "{m.name}") {{']
            lines += ["        " + l for l in call_expr(c.name, m)]
            lines.append("    }")
            (streams if m.stream else rest).extend(lines)
            table.append({"class": c.name, "method": m.name, "stream": m.stream,
                          "params": [{"name": n, "type": t, "required": r,
                                      "default": default_text(d)}
                                     for n, t, d, r in m.params]})
    out = ["// Generated by tools/gen_calls.py from python-openhab-rest-client – do not edit.",
           '#include "calls.hpp"', "",
           "namespace {",
           "using openhab::json;",
           "const json NONE = nullptr;",
           "const json& a_(const json& o, const char* n) {",
           "    auto it = o.find(n);",
           "    return it == o.end() ? NONE : *it;",
           "}",
           "std::string s_(const json& v) { return v.is_string() ? v.get<std::string>() : \"\"; }",
           "bool b_(const json& v) { return v.is_boolean() && v.get<bool>(); }",
           "int i_(const json& v) { return v.is_number() ? v.get<int>() : 0; }",
           "double d_(const json& v) { return v.is_number() ? v.get<double>() : 0; }",
           "const json& j_(const json& v) { return v; }",
           "// optional arguments: only set what the request contains (null = None)",
           "template <class T> void set_(T& t, const json& o, const char* n) {",
           "    auto it = o.find(n);",
           "    if (it == o.end()) return;",
           "    if (it->is_null()) t = T();",
           "    else t = it->template get<T>();",
           "}",
           "template <class T> void set_(std::optional<T>& t, const json& o, const char* n) {",
           "    auto it = o.find(n);",
           "    if (it == o.end()) return;",
           "    if (it->is_null()) t.reset();",
           "    else t = it->template get<T>();",
           "}",
           "void set_(json& t, const json& o, const char* n) {",
           "    auto it = o.find(n);",
           "    if (it != o.end()) t = *it;",
           "}",
           "}  // namespace", "",
           "std::optional<openhab::json> openhabCall(openhab::OpenHABClient& c, const std::string& cls,",
           "                                         const std::string& m, const openhab::json& args) {",
           *rest, "    return std::nullopt;", "}", "",
           "std::optional<openhab::EventStream> openhabOpenStream(openhab::OpenHABClient& c,",
           "                                                      const std::string& cls,",
           "                                                      const std::string& m,",
           "                                                      const openhab::json& args) {",
           *streams, "    return std::nullopt;", "}", ""]
    open(sys.argv[3], "w").write("\n".join(out))
    json.dump(table, open(sys.argv[4], "w"), indent=1, ensure_ascii=False)
    print(f"{sum(1 for t in table if not t['stream'])} REST methods, "
          f"{sum(1 for t in table if t['stream'])} event streams")


main()
